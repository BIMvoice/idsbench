// Regenerates src/schemas.generated.ts from schemas/*.xsd so the validator needs no file or network access at runtime.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

// The notice every source file of the repository carries (scripts/check-headers.mjs checks that it is at the top).
const NOTICE = '/* This Source Code Form is subject to the terms of the Mozilla Public\n * License, v. 2.0. If a copy of the MPL was not distributed with this\n * file, You can obtain one at https://mozilla.org/MPL/2.0/. */\n';
const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const files = { ids10: 'ids-1.0.xsd', xml: 'xml.xsd', xmlSchema: 'XMLSchema.xsd' };
let out = NOTICE + '// GENERATED by scripts/build-schemas.mjs from schemas/*.xsd. Do not edit.\n';
for (const [k, f] of Object.entries(files)) {
  const text = readFileSync(join(root, 'schemas', f), 'utf8').replace(/^﻿/, '');
  out += `export const ${k}: string = ${JSON.stringify(text)};\n`;
}
writeFileSync(join(root, 'src', 'schemas.generated.ts'), out);
console.log('wrote src/schemas.generated.ts');
